@dataclass(frozen=True)
class ModelSpec:
    provider: str
    model: str
    label: str


def get_langsmith_project() -> str:
    return (
        os.environ.get("LANGSMITH_PROJECT")
        or os.environ.get("LANGCHAIN_PROJECT")
        or "ScholarSync"
    )


def ensure_langsmith_env() -> None:
    project = get_langsmith_project()
    os.environ["LANGSMITH_PROJECT"] = project
    os.environ["LANGCHAIN_PROJECT"] = project
    if (os.environ.get("LANGSMITH_API_KEY") or "").strip():
        os.environ["LANGSMITH_TRACING_ENABLED"] = "true"
        os.environ["LANGCHAIN_TRACING_V2"] = "true"


def dataset_name(agent_id: str) -> str:
    return f"nbm-prompt-{agent_id}"


def _load_models_config() -> Dict[str, Any]:
    if not MODELS_CONFIG_PATH.is_file():
        return {"agents": {}}
    return json.loads(MODELS_CONFIG_PATH.read_text(encoding="utf-8"))


def infer_provider(model_id: str) -> str:
    m = (model_id or "").lower().strip()
    if m.startswith("gpt-") or m.startswith("o1") or m.startswith("o3"):
        return "openai"
    if m.startswith("claude-"):
        return "anthropic"
    if m.startswith("gemini-"):
        return "gemini"
    if m.startswith("deepseek-"):
        return "deepseek"
    return "unknown"


def get_agent_models(agent_id: str) -> List[ModelSpec]:
    """Per-agent model matrix from agent_models.json (generated by extract script)."""
    doc = _load_models_config()
    entries = (doc.get("agents") or {}).get(agent_id) or []
    specs: List[ModelSpec] = []
    for entry in entries:
        model_id = str(entry.get("model") or "").strip()
        if not model_id or model_id.upper().startswith("N/A"):
            continue
        provider = str(entry.get("provider") or infer_provider(model_id)).lower()
        if entry.get("skip"):
            continue
        label = f"{provider}-{model_id}".replace("/", "-")
        specs.append(ModelSpec(provider=provider, model=model_id, label=label))
    if not specs and agent_id in SCOPE_AGENT_IDS:
        from evals.agent_eval.registry import DEFAULT_FALLBACK_MODELS

        for entry in DEFAULT_FALLBACK_MODELS:
            specs.append(
                ModelSpec(
                    provider=entry["provider"],
                    model=entry["model"],
                    label=f"{entry['provider']}-{entry['model']}",
                )
            )
    return specs
